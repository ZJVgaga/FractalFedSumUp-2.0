    class FunnelEncoder(nn.Module):
        def __init__(self, raw_dim, latent_dim):
            super().__init__()
            self.raw_dim = raw_dim
            self.latent_dim = latent_dim
            self.W = nn.Linear(raw_dim, latent_dim, bias=False)
            self.core = nn.Sequential(
                nn.Linear(latent_dim, 256),
                nn.ReLU(),
                nn.Linear(256, latent_dim)
            )
        
        def forward(self, x):
            batch_size = x.shape[0]
            if x.shape[-1] == self.raw_dim:
                z = self.W(x)
            elif x.shape[-1] == self.latent_dim:
                zeros = torch.zeros(batch_size, self.raw_dim - self.latent_dim, device=x.device)
                x_padded = torch.cat([x, zeros], dim=-1)
                z = self.W(x_padded)
            else:
                raise ValueError(f"输入维度 {x.shape[-1]} 不匹配 {self.raw_dim} 或 {self.latent_dim}")
            return self.core(z)
        
        def encode(self, x):
            batch_size = x.shape[0]
            x_flat = x.view(batch_size, -1)
            if x_flat.shape[-1] != self.raw_dim:
                raise ValueError(f"输入展平后维度 {x_flat.shape[-1]} 不匹配 raw_dim {self.raw_dim}")
            z = self.forward(x_flat)
            return z, z, torch.zeros_like(z)
        
        def decode(self, z, original_shape=None):
            batch_size = z.shape[0]
            if original_shape is not None:
                return torch.zeros(original_shape, device=z.device)
            else:
                return torch.zeros(batch_size, self.raw_dim, device=z.device).view(
                    batch_size, -1, 1, 1
                )
    
